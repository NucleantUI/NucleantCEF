//
//  CEFKeyMap.swift
//  NucleantCEF
//
//  macOS virtual key codes (`NSEvent.keyCode`, the kVK_* constants) to what
//  CEF's key events want beside them. On macOS CEF rebuilds the platform
//  event from `native_key_code` and the characters, so the Windows key code
//  is a courtesy — but pages read `event.keyCode`, and a correct one costs a
//  table.
//

import NucleantUI

enum CEFKeyMap {

    /// The Windows virtual key code (VK_*) for `keyCode`, or for the typed
    /// character when the key has no fixed meaning here.
    static func windowsKeyCode(forKeyCode keyCode: UInt16, character: UInt16) -> Int {
        if let code = table[keyCode] { return code }
        // A layout-dependent key: what it typed decides, as on Windows.
        switch character {
        case 0x61...0x7A: return Int(character) - 0x20   // a–z → VK_A…VK_Z
        case 0x41...0x5A, 0x30...0x39: return Int(character)
        default: return 0
        }
    }

    /// The editing command a ⌘-chord stands for, if it is one.
    static func editCommand(forKeyCode keyCode: UInt16, shift: Bool) -> EditCommand? {
        switch keyCode {
        case 0x06: return shift ? .redo : .undo   // Z
        case 0x07: return .cut                    // X
        case 0x08: return .copy                   // C
        case 0x09: return .paste                  // V
        case 0x00: return .selectAll              // A
        default:   return nil
        }
    }

    private static let table: [UInt16: Int] = [
        // Letters (ANSI positions).
        0x00: 0x41, 0x0B: 0x42, 0x08: 0x43, 0x02: 0x44, 0x0E: 0x45, 0x03: 0x46, 0x05: 0x47,
        0x04: 0x48, 0x22: 0x49, 0x26: 0x4A, 0x28: 0x4B, 0x25: 0x4C, 0x2E: 0x4D, 0x2D: 0x4E,
        0x1F: 0x4F, 0x23: 0x50, 0x0C: 0x51, 0x0F: 0x52, 0x01: 0x53, 0x11: 0x54, 0x20: 0x55,
        0x09: 0x56, 0x0D: 0x57, 0x07: 0x58, 0x10: 0x59, 0x06: 0x5A,
        // Digits.
        0x1D: 0x30, 0x12: 0x31, 0x13: 0x32, 0x14: 0x33, 0x15: 0x34,
        0x17: 0x35, 0x16: 0x36, 0x1A: 0x37, 0x1C: 0x38, 0x19: 0x39,
        // Punctuation (VK_OEM_*).
        0x29: 0xBA, 0x18: 0xBB, 0x2B: 0xBC, 0x1B: 0xBD, 0x2F: 0xBE, 0x2C: 0xBF,
        0x32: 0xC0, 0x21: 0xDB, 0x2A: 0xDC, 0x1E: 0xDD, 0x27: 0xDE,
        // Editing and navigation.
        0x33: 0x08,  // delete (backspace) → VK_BACK
        0x30: 0x09,  // tab
        0x24: 0x0D,  // return
        0x4C: 0x0D,  // keypad enter
        0x35: 0x1B,  // escape
        0x31: 0x20,  // space
        0x74: 0x21,  // page up
        0x79: 0x22,  // page down
        0x77: 0x23,  // end
        0x73: 0x24,  // home
        0x7B: 0x25,  // left
        0x7E: 0x26,  // up
        0x7C: 0x27,  // right
        0x7D: 0x28,  // down
        0x75: 0x2E,  // forward delete → VK_DELETE
        // Modifiers.
        0x38: 0x10, 0x3C: 0x10,  // shift
        0x3B: 0x11, 0x3E: 0x11,  // control
        0x3A: 0x12, 0x3D: 0x12,  // option → VK_MENU
        0x37: 0x5B, 0x36: 0x5C,  // command → VK_LWIN / VK_RWIN
        0x39: 0x14,              // caps lock
        // Function keys.
        0x7A: 0x70, 0x78: 0x71, 0x63: 0x72, 0x76: 0x73, 0x60: 0x74, 0x61: 0x75,
        0x62: 0x76, 0x64: 0x77, 0x65: 0x78, 0x6D: 0x79, 0x67: 0x7A, 0x6F: 0x7B,
    ]
}
